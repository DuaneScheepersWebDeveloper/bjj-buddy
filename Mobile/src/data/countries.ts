/** Up to `limit` countries matching what's typed: names that start with it first, then names containing it. */
export function searchCountries(query: string, limit = 6): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const starts = COUNTRIES.filter((c) => c.toLowerCase().startsWith(q));
  const contains = COUNTRIES.filter((c) => !c.toLowerCase().startsWith(q) && c.toLowerCase().includes(q));
  return [...starts, ...contains].slice(0, limit);
}
